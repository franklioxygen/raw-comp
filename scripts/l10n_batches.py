def merged_locale_mapping(locale: str, base: dict[str, str]) -> dict[str, str]:
    from l10n_complete import COMPLETE
    from l10n_remaining import REMAINING
    from l10n_finalize import FINALIZE
    from l10n_technical import TECHNICAL

    mapping = dict(base)
    mapping.update(COMPARE_MODES.get(locale, {}))
    mapping.update(CORE_ADJUSTMENTS.get(locale, {}))
    mapping.update(REMAINING.get(locale, {}))
    mapping.update(TECHNICAL.get(locale, {}))
    mapping.update(FINALIZE.get(locale, {}))
    mapping.update(COMPLETE.get(locale, {}))
    return mapping
